"""Emit fixed protocol/mode tables used by synthesizable RTL and test fixtures."""
from reference import ROOT,MFSK_TABLE
from modes import MODES,frame_count,parameters
import math

header='// Generated by scripts/psk/generate_tables.py; do not edit by hand.\n'
body=header+'`define PSK_MODE_COUNT '+str(len(MODES))+'\n'
for func,width,field in [('mode_family',2,1),('mode_rate',3,2),('mode_label',72,0)]:
    body+=f'function [{width-1}:0] {func};\ninput [4:0] index;\nbegin case(index)\n'
    for i,mode in enumerate(MODES):
        value=f'"{mode[field]:<9}"' if field==0 else f"{width}'d{mode[field]}"
        body+=f"5'd{i}:{func}={value};\n"
    value='"BPSK31   "' if field==0 else f"{width}'d0"
    body+=f'default:{func}={value};\nendcase end\nendfunction\n'
for key,width in [('carriers',4),('k',5),('p0',16),('p1',16),('depth',10),('puncture',1),('mfsk',1)]:
    body+=f'function [{width-1}:0] mode_{key};\ninput [4:0] index;\nbegin case(index)\n'
    for i,(name,_,_) in enumerate(MODES):
        body+=f"5'd{i}:mode_{key}={width}'d{parameters(name)[key]};\n"
    body+=f"default:mode_{key}={width}'d{1 if key=='carriers' else 0};\nendcase end\nendfunction\n"
body+='function [31:0] carrier_step;\ninput [4:0] index;input [3:0] carrier;\nbegin case(index)\n'
for i,(name,_,_) in enumerate(MODES):
    p=parameters(name)
    if p['carriers']==1: continue
    body+=f"5'd{i}:case(carrier)\n"
    for c in range(p['carriers']):
        hz=2000+(c-(p['carriers']-1)/2)*1.4*p['baud']
        body+=f"4'd{c}:carrier_step=32'd{round(hz/16000*2**32)}; // {hz:g} Hz\n"
    body+="default:carrier_step=32'd536870912;\nendcase\n"
body+='default:carrier_step=32\'d536870912;\nendcase end\nendfunction\n'
(ROOT/'rtl/psk/mode_config.vh').write_text(body,newline='\n')
body=header+''.join(f"sine_rom[{i}]=12'sd{round(2047*math.sin(2*math.pi*i/1024))};\n".replace("12'sd-","-12'sd") for i in range(1024))
(ROOT/'rtl/psk/sine_init.vh').write_text(body,newline='\n')
body=header+'function signed [15:0] rx_fir_coeff;\ninput [2:0] rate;input [5:0] tap;\nbegin case({rate==6,rate==7})\n'
for rate,sps in [(0,16),(6,20),(7,13)]:
    count=41 if rate==6 else 33
    h=[(1 if i==(count-1)/2 else math.sin(math.pi*(i-(count-1)/2)*2/sps)/(math.pi*(i-(count-1)/2)*2/sps))*(.54-.46*math.cos(2*math.pi*i/(count-1))) for i in range(count)]
    total=sum(h)
    body+=f"2'd{2 if rate==6 else 1 if rate==7 else 0}:case(tap)\n"
    body+=''.join(f"6'd{i}:rx_fir_coeff=16'sd{round(v/total*32768)};\n".replace("16'sd-","-16'sd") for i,v in enumerate(h))
    body+="default:rx_fir_coeff=0;endcase\n"
body+='default:rx_fir_coeff=0;endcase end\nendfunction\n'
(ROOT/'rtl/psk/rx_fir_coeff.vh').write_text(body,newline='\n')
body=header+'// MFSK Varicode wire codes used by HPM uncoded 8PSK text.\n'
body+='function [7:0] mfsk_decode;\ninput [10:0] code;\nbegin case(code)\n'
body+=''.join(f"11'h{code:03x}:mfsk_decode=8'd{i};\n" for i,code in enumerate(MFSK_TABLE[:128]) if i and code<2048)
body+='default:mfsk_decode=0;\nendcase end\nendfunction\n'
(ROOT/'rtl/psk/mfsk_varicode.vh').write_text(body,newline='\n')
body=header+'case(mode_index)\n'
for i,(name,_,rate) in enumerate(MODES):
    frames=frame_count(rate,name)
    body+=f'{i}:begin frames={frames};$readmemh({{VECTOR_DIR,"{name}.hex"}},samples,0,{frames-1});f=$fopen("{name}.txt","w");end\n'
body+='endcase\n'
(ROOT/'sim/psk/vector_files.vh').write_text(body,newline='\n')
print(f'Generated mode and Varicode tables for {len(MODES)} modes')
